// ============================================================
// DRUM_STYLE_PATTERNS
// Redesigned: richer grooves, ghost notes, more character
// Each pattern is a 16th-note grid for 4/4, 12th for 3/4 & 6/8
// Keys: kick, snare, hihat, openHat, rim, clap (new percussion)
// ============================================================

export type DrumPattern = {
  kick: number[]
  snare: number[]
  hihat: number[]
  openHat: number[]
  rim: number[]
  clap: number[]
}

export type DrumStylePatterns = Record<string, Record<string, DrumPattern>>

function p(
  kick: string,
  snare: string,
  hihat: string,
  openHat: string = "0".repeat(kick.length),
  rim: string = "0".repeat(kick.length),
  clap: string = "0".repeat(kick.length),
): DrumPattern {
  const parse = (s: string) => s.split("").map(Number)
  return {
    kick: parse(kick),
    snare: parse(snare),
    hihat: parse(hihat),
    openHat: parse(openHat),
    rim: parse(rim),
    clap: parse(clap),
  }
}

